import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Система, на якій записані еталонні знімки з теки `goldens/`.
///
/// Одне й те саме дерево віджетів на різних системах малюється не однаково.
/// Згладжування країв і розсіювання градієнта рахуються числами з комою, а
/// останній біт такого числа на arm64 і на x64 різний. Оком цього не видно, а
/// для порівняння піксель у піксель різниця величезна: збірка на macOS дала
/// розбіжність 3.7% на сторінці теми і 2.5% на переході між датами, не маючи в
/// коді жодної правки.
///
/// Знімки самої рідини те саме порівняння пройшли: там немає ні тексту, ні
/// довгих градієнтів, тобто нічого, у чому розходяться округлення. Тобто це не
/// поламані еталони, а межа самого способу перевірки.
const goldenHost = 'windows';

/// Порівняти намальоване з еталоном `goldens/[name]`.
///
/// На чужій системі знімок не порівнюється, тест позначається пропущеним і
/// каже чому. Решта перевірок усередині нього працює скрізь: пропускається
/// саме порівняння пікселів, а не тест.
///
/// Так, а не послабленим допуском: допуск, під який пролазить різниця в три
/// відсотки, пропустить і справжню зміну вигляду, а вона і є те, заради чого
/// знімок знімали. І не мовчазним `if`: у журналі збірки має бути видно, що
/// саме тут не перевірялось.
Future<void> matchesGolden(Finder what, String name) async {
  if (Platform.operatingSystem != goldenHost) {
    markTestSkipped('еталони знято на $goldenHost, а тут ${Platform.operatingSystem}');
    return;
  }
  await expectLater(what, matchesGoldenFile('goldens/$name'));
}
