import 'package:flutter_test/flutter_test.dart';

import 'package:calvi/data/measure.dart';

/// Число і слово при ньому, за українським правилом.
///
/// «5 дні тому» стояло на головному екрані місяцями: правило зводилось до
/// «менше семи означає дні», а насправді дві-чотири це дні, а пʼять і далі днів.
void main() {
  test('дні відмінюються, а не приклеюються', () {
    expect(measureAgo(0), 'сьогодні');
    expect(measureAgo(-1), 'учора');
    expect(measureAgo(-2), '2 дні тому');
    expect(measureAgo(-4), '4 дні тому');
    expect(measureAgo(-5), '5 днів тому');
    expect(measureAgo(-6), '6 днів тому');
  });

  test('тижні теж', () {
    expect(measureAgo(-7), 'тиждень тому');
    expect(measureAgo(-21), '3 тижні тому');
    expect(measureAgo(-35), '5 тижнів тому');
  });

  test('одинадцять це виняток, а не одиниця', () {
    /* Найпідступніша частина правила: за останньою цифрою одинадцять схоже на
       одиницю, а поводиться як пʼять. Рахує це вже не наш код, а ICU, і саме
       тому перевірка лишається: підміна множини на «$n + слово» повернула б
       «11 день». */
    expect(measureAgo(-77), '11 тижнів тому');
    expect(measureAgo(-147), '21 тиждень тому');
    expect(measureAgo(-154), '22 тижні тому');
  });
}
