import 'package:flutter_test/flutter_test.dart';

import 'package:calvi/data/meal.dart';

/* Назва запису це те, що людина бачить у картці дня щодня.
 *
 * Записи від Нори приходять із сервера вже з великої літери. Тут перевіряється
 * те, що людина вписала руками: рядок «яйце» поруч із «Тост з маслом» читається
 * як недогляд застосунку, а не як її почерк.
 */
void main() {
  test('назва починається з великої літери', () {
    expect(titled('яйце'), 'Яйце');
    expect(titled('борщ домашній'), 'Борщ домашній');
    expect(titled('chicken with rice'), 'Chicken with rice');
    expect(titled('żurek'), 'Żurek');
  });

  test('решта назви лишається як була', () {
    // Не «Тост З Маслом»: підпис, а не вивіска.
    expect(titled('тост з Маслом'), 'Тост з Маслом');
    expect(titled('кава latte'), 'Кава latte');
  });

  test('цифра на початку лишається цифрою', () {
    expect(titled('100% сік'), '100% сік');
  });

  test('пробіли по краях знімаються, порожнє лишається порожнім', () {
    expect(titled('  яйце  '), 'Яйце');
    expect(titled(''), '');
    expect(titled('   '), '');
  });
}
