import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';

/// Службові звуки початку і кінця запису голосу.
///
/// **Тільки на iOS, і це головне тут.** На Android розпізнаванням займається
/// окремий системний сервіс, і він грає власні службові звуки. Свій поверх
/// системного дав би два звуки на одне натискання, а це гірше за жоден.
///
/// На iOS розпізнавання йде прямо в процесі застосунку, `SFSpeechRecognizer`, і
/// ніяких звуків Apple для нього не передбачила. Тому їх треба мати своїми.
///
/// Звук іде через `AudioServicesPlaySystemSound`, а не через програвач.
/// Причина в аудіосесії: під час диктування вона стоїть у режимі запису, і
/// звичайний програвач став би її переналаштовувати рівно тієї миті, коли
/// мікрофон вмикається або щойно вимкнувся. Системний виклик у сесію не лізе,
/// він для коротких службових сигналів і зроблений.
class Earcon {
  const Earcon._();

  static const _channel = MethodChannel('calvi/earcon');

  /// Чи ця система взагалі щось від нас чекає.
  ///
  /// Читається щоразу, а не запамʼятовується: тест міняє платформу між
  /// перевірками, і поле, обчислене один раз, зробило б другу перевірку
  /// беззмістовною.
  static bool get _wanted => defaultTargetPlatform == TargetPlatform.iOS;

  /// Запис почався.
  static Future<void> start() => _play('duo-on');

  /// Запис закінчився.
  static Future<void> stop() => _play('duo-off');

  static Future<void> _play(String name) async {
    if (!_wanted) return;
    try {
      await _channel.invokeMethod<void>('play', name);
    } catch (_) {
      /* Мовчки. Службовий звук це приємність, а не робота: телефон у
         беззвучному режимі, зайнята аудіосистема чи будь-яка інша відмова не
         має ні зупиняти диктування, ні показувати людині помилку про звук,
         якого вона все одно не просила. */
    }
  }
}
