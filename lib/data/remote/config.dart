/// Where the app looks for its server.
///
/// За замовчуванням це бойовий сервер: збірка, зроблена без жодного прапорця,
/// має працювати в людини на телефоні, а не тільки в тій самій кімнаті, що й
/// машина розробника. Помилитись тут дорого і тихо, тому правильне значення
/// стоїть саме як типове.
///
/// Домашній сервер вмикається прапорцем, коли він потрібен:
///
///     flutter run --dart-define=CALVI_API=http://192.168.50.51:8090
///
/// Дозвіл на звичайний http у маніфесті лишається рівно для цих домашніх адрес.
/// На calvi.uk застосунок ходить по https, і саме тому там нічого дозволяти не
/// треба.
const apiBase = String.fromEnvironment('CALVI_API', defaultValue: 'https://calvi.uk');

/// Веб-клієнт із консолі Google, для входу через акаунт.
///
/// Саме веб, а не Android: цей ідентифікатор наш сервер перевіряє як адресата
/// токена. Помилка тут виглядає як «вікно Google відкрилось, а вхід не
/// проходить», і шукається довго.
///
/// Значення стоїть тут, а не тільки в рядку збірки.
///
/// Таємниці в ньому немає: це ідентифікатор застосунку, а не ключ від нього, і
/// він однаково видно в коді сторінки входу на сайті. А от забути прапорець
/// `--dart-define` легко, і ціна цього тиха: збірка виходить без кнопки входу
/// зовсім. Особливо коли файл збирає не термінал, а майстер Android Studio,
/// якому прапорця не передаси.
///
/// Порожнє значення однаково лишається робочим станом: кнопка тоді не
/// показується, бо кнопка, яка нічого не робить, гірша за її відсутність.
///
///     flutter build appbundle --dart-define=CALVI_GOOGLE_CLIENT=...apps.googleusercontent.com
