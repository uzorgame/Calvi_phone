/// Рецепт першою реплікою чату: Нора бачить складники і кроки без нового
/// маршруту на сервері. Це текст до моделі, не напис на екрані.
String recipeChatContext(RecipeData r) {
  final items = [for (final i in r.items) '${i.name} ${i.grams} г'].join(', ');
  return 'Контекст: мій рецепт «${r.title}». '
      'Порція ${r.gramsPerServing} г: ${r.kcal} ккал, Б ${r.protein}, Ж ${r.fat}, В ${r.carbs}. '
      'Складники: $items. Кроки: ${r.steps.join(' ')}';
}
