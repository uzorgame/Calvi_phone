import 'package:drift/drift.dart';

import 'synced.dart';

/// Ціль, яка діяла з певного дня.
///
/// Профіль тримає ціль поточну, і за нею рахується норма. Тут лежить те, чого в
/// ньому немає: минуле. Картка дня показує будь-який день, і дуга на ній має
/// міряти шлях до тієї цілі, яка діяла тоді, а не до сьогоднішньої. Без цієї
/// таблиці зміна цілі переписувала б увесь минулий місяць заднім числом.
///
/// Один рядок на день: людина може крутити повзунок скільки завгодно, і кожен
/// рух не має ставати окремим рішенням в історії. Лишається те, на якому вона
/// зупинилась.
class Goals extends Table with Synced {
  /// Місцевий день людини, з якого діє ця ціль.
  TextColumn get startedOn => text().withLength(min: 10, max: 10)();

  /// Вага, від якої міряється шлях. Порожня буває в цілі «тримати вагу».
  RealColumn get goalStartKg => real().nullable()();
  RealColumn get targetKg => real().nullable()();

  TextColumn get direction => text().withLength(max: 10)();

  /// Кілограмів на тиждень, завжди додатне: знак задає напрямок.
  RealColumn get pace => real()();
}
