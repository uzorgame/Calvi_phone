import 'settings.dart';

/// Ціль, яка діяла з певного дня.
///
/// Налаштування тримають ціль поточну, і за нею рахується норма. Цей запис
/// відповідає на інше питання: яка ціль була такого-то числа. Без нього зміна
/// цілі переписувала б минулі картки дня заднім числом, ніби людина завжди
/// йшла туди, куди зібралась сьогодні.
///
/// Живе в базі телефона, їздить синхронізацією і переживає перевстановлення.
class GoalAt {
  const GoalAt({
    required this.from,
    required this.startKg,
    required this.targetKg,
    required this.direction,
    this.pace = 0.5,
  });

  /// День, з якого діє ця ціль. Відлік від сьогодні, як усі дати в застосунку.
  final int from;

  /// Вага в день, коли ціль поставили: від неї міряється пройдений шлях.
  final double startKg;
  final double targetKg;
  final Direction direction;

  /// Кілограмів на тиждень, завжди додатне: знак задає напрямок.
  final double pace;
}

/* Одна ціль у демонстраційній історії: поставлена два місяці тому, 81 кг на
   старті й 74 в цілі. Саме її бачить уся демо-історія, і вага в ній рухається
   від 81.4 до 78.6. Ті самі числа стоять у демці на 5300. */
const demoGoals = <GoalAt>[
  GoalAt(from: -60, startKg: 81, targetKg: 74, direction: Direction.lose),
];
