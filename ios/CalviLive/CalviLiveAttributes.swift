import ActivityKit
import Foundation

/* Що саме показує живий запис дня.
 *
 * Один файл на два боки: його компілює і сам застосунок, який заводить і оновлює
 * активність, і розширення, яке її малює. Дві копії того самого типу означали б
 * розбіжність у форматі на першій же правці, а розбіжність тут тиха: активність
 * просто перестає оновлюватись.
 *
 * Числа рахує Dart і передає вже готовими. Розширення нічого не рахує саме: воно
 * не має ні бази, ні норми, ні поняття про тренування.
 */
struct CalviLiveAttributes: ActivityAttributes {
  public struct ContentState: Codable, Hashable {
    /// Скільки лишилось до норми. Відʼємне означає перебір.
    var left: Int

    /// Норма дня.
    var goal: Int

    /// Скільки вже зʼїдено, нетто: спалене на тренуваннях уже відняте.
    var eaten: Int

    /* Скільки калорій в останньому записі, або порожньо, коли сьогодні ще
       нічого не записували. Показує його лише розгорнутий вигляд: у стислому
       на нього немає ні місця, ні потреби. */
    var last: Int?

    /// Перебір це не мінус на екрані, а інше слово поруч із додатним числом.
    var over: Bool { left < 0 }

    /// Скільки норми пройдено, 0...1. Кільце і смуга беруть саме її.
    var progress: Double {
      guard goal > 0, eaten > 0 else { return 0 }
      return min(1, Double(eaten) / Double(goal))
    }

    /// Число, яке видно: завжди додатне.
    var shown: Int { abs(left) }
  }

  /// Сталого в цій активності немає: усе, що вона показує, міняється протягом
  /// дня. Поле лишається порожнім навмисно, бо `ActivityAttributes` вимагає
  /// типу, а вигадувати йому вміст тільки заради форми не варто.
  var day: String = ""
}
