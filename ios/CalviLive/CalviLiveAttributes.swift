import ActivityKit
import Foundation

/* Що саме показує живий запис дня.
 *
 * Один файл на два боки: його компілює і сам застосунок, який заводить і оновлює
 * активність, і розширення, яке її малює. Дві копії того самого типу означали б
 * розбіжність у форматі на першій же правці, а розбіжність тут тиха: активність
 * просто перестає оновлюватись.
 *
 * **Слова приходять готовими з Dart, як і на Android.** Тут їх не складають і
 * не перекладають: у розширення не дістає ні `BuildContext`, ні локаль
 * застосунку, і будь-який зашитий рядок лишався б українським у німецькому
 * телефоні. Саме так і було: «ккал лишилось» бачив кожен, хай якою мовою він
 * поставив застосунок. Числа теж приходять готовими, бо рахує їх щоденник.
 *
 * Звідси й форма полів: не «скільки зʼїдено», а «що написати». Розширення
 * малює, і більше нічого не робить.
 */
struct CalviLiveAttributes: ActivityAttributes {
  public struct ContentState: Codable, Hashable {
    /// Скільки норми пройдено, 0...1. Кільце і смуга беруть саме її.
    var progress: Double

    /// Велике число: скільки лишилось або на скільки перебір. Завжди додатне,
    /// уже з розділювачем тисяч, бо пише його той самий код, що й картку дня.
    var shown: String

    /// Підпис під ним: «ккал лишилось» або «ккал перебір».
    var caption: String

    /// Те саме для замкненого екрана, де місця більше: «лишилось на сьогодні».
    var lock: String

    /// «ккал» біля великого числа на замкненому екрані.
    var unit: String

    /* Рядок про останній запис. Порожнє значення означає, що сьогодні ще нічого
       не записували, і тоді підпис каже саме це. Назви страви немає навмисно:
       острівець видно не лише тому, кому він призначений. */
    var lastLabel: String
    var lastValue: String
  }

  /// Сталого в цій активності немає: усе, що вона показує, міняється протягом
  /// дня. Поле лишається порожнім навмисно, бо `ActivityAttributes` вимагає
  /// типу, а вигадувати йому вміст тільки заради форми не варто.
  var day: String = ""
}
